// Extracts the game-icons.net glyphs we use into src/ui/hud/icons.ts (CC BY 3.0, see CREDITS.md).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const set = JSON.parse(readFileSync(require.resolve('@iconify-json/game-icons/icons.json'), 'utf8')) as { icons: Record<string, { body: string }> };
const WANT = [
  'broadsword', 'checked-shield', 'cloak-dagger', 'crossed-swords', 'sword-clash', 'hearts', 'lightning-helix', 'crowned-skull',
  'wolf-head', 'troll', 'dragon-head', 'spider-face', 'snake', 'golem-head', 'hooded-assassin', 'spectre', 'visored-helm', 'moon',
  'skull-crossed-bones', 'potion-ball', 'run', 'castle', 'death-skull', 'bandit', 'scythe', 'swords-emblem', 'winged-sword',
  'two-coins', 'scroll-unfurled', 'dice-six-faces-six', 'shop', 'campfire', 'crystal-ball', 'trophy-cup', 'sun', 'sands-of-time',
];
const lines = WANT.map((n) => {
  const icon = set.icons[n];
  if (!icon) throw new Error(`missing icon ${n}`);
  return `  '${n}': ${JSON.stringify(icon.body)},`;
});
writeFileSync('src/ui/hud/icons.ts', `// Generated by scripts/gen-icons.ts from game-icons.net (CC BY 3.0, Lorc, Delapouite and contributors).\n/* eslint-disable */\nexport const ICONS: Record<string, string> = {\n${lines.join('\n')}\n};\n\n/** Inline SVG markup for an icon (512x512 viewBox, currentColor). */\nexport function icon(name: string, cls = ''): string {\n  return \`<svg class="ico \${cls}" viewBox="0 0 512 512" aria-hidden="true">\${(ICONS[name] ?? '').replace(/fill="#fff"/g, 'fill="currentColor"')}</svg>\`;\n}\n`);
console.log(`wrote ${WANT.length} icons`);
