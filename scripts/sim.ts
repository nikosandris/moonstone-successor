// Headless bot-vs-bot simulation. Usage: npm run sim [-- --games 1000 --seed 1 --out docs/balance-report.md]
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { botAction } from '../src/core/bot';
import { applyAction, createGame } from '../src/core/game';
import { ITEMS } from '../src/data/items';
import { CONFIG } from '../src/data/balance';
import type { GameState } from '../src/core/types';

const args = process.argv.slice(2);
const arg = (name: string, def: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : def;
};
const GAMES = Number(arg('games', '1000'));
const SEED0 = Number(arg('seed', '1'));
const OUT = arg('out', 'docs/balance-report.md');
const PLAYERS = 4;

function playGame(seed: number): GameState {
  let s = createGame(
    Array.from({ length: PLAYERS }, (_, i) => ({ name: `Bot ${i + 1}`, color: 0, bot: true })),
    seed,
  );
  let guard = 0;
  while (s.stage !== 'gameOver') {
    s = applyAction(s, botAction(s));
    if (++guard > 200000) throw new Error(`game ${seed} did not terminate`);
  }
  return s;
}

const t0 = Date.now();
let sanctum = 0;
let capped = 0;
let daysSum = 0;
const wins = Array(PLAYERS).fill(0);
const winsBySanctum = Array(PLAYERS).fill(0);
let deaths = 0;
let kills = 0;
const itemUse: Record<string, number> = {};
const dayHist: Record<string, number> = {};
for (let g = 0; g < GAMES; g++) {
  const s = playGame(SEED0 + g);
  if (s.endReason === 'sanctum') sanctum++;
  else capped++;
  daysSum += s.day;
  wins[s.winner!]++;
  if (s.endReason === 'sanctum') winsBySanctum[s.winner!]++;
  for (const p of s.players) { deaths += p.deaths; kills += p.kills; }
  for (const [id, n] of Object.entries(s.stats.itemUse)) itemUse[id] = (itemUse[id] ?? 0) + n;
  const bucket = `${Math.floor((s.day - 1) / 4) * 4 + 1}-${Math.floor((s.day - 1) / 4) * 4 + 4}`;
  dayHist[bucket] = (dayHist[bucket] ?? 0) + 1;
}

const pct = (n: number) => `${((n / GAMES) * 100).toFixed(1)}%`;
const used = ITEMS.map((i) => ({ item: i, n: itemUse[i.id] ?? 0 })).sort((a, b) => b.n - a.n);
const unit = (it: (typeof ITEMS)[number]) => (it.kind === 'consumable' ? 'uses' : 'combat rounds equipped');
const row = (u: (typeof used)[number]) => `| ${u.item.name} | ${u.item.kind} (T${u.item.tier}) | ${u.n} (${unit(u.item)}) |`;
const maxWin = Math.max(...wins) / GAMES;
const sanctumPct = sanctum / GAMES;
const avgDays = daysSum / GAMES;

const report = `# Balance report

Generated by \`npm run sim\` (${GAMES} bot-vs-bot games, ${PLAYERS} knights, seeds ${SEED0}..${SEED0 + GAMES - 1}, ${((Date.now() - t0) / 1000).toFixed(1)}s).

## Targets

| Metric | Target | Result | Pass |
| --- | --- | --- | --- |
| Games ending by Sanctum | > 70% | ${(sanctumPct * 100).toFixed(1)}% | ${sanctumPct > 0.7 ? 'yes' : 'NO'} |
| Average game length | 15 - 30 days | ${avgDays.toFixed(1)} days | ${avgDays >= 15 && avgDays <= 30 ? 'yes' : 'NO'} |
| Max single-seat win rate | <= 35% | ${(maxWin * 100).toFixed(1)}% | ${maxWin <= 0.35 ? 'yes' : 'NO'} |

## Results

- Ended by Sanctum: ${sanctum} (${pct(sanctum)})
- Ended by day cap (${CONFIG.dayCap}): ${capped} (${pct(capped)})
- Average length: ${avgDays.toFixed(2)} days

### Win distribution per seat

| Seat | Wins | Share | of which by Sanctum |
| --- | --- | --- | --- |
${wins.map((w, i) => `| ${i + 1} | ${w} | ${pct(w)} | ${winsBySanctum[i]} |`).join('\n')}

### Game length histogram (day of game end)

| Days | Games |
| --- | --- |
${Object.entries(dayHist).map(([k, v]) => `| ${k} | ${v} |`).join('\n')}

### Deaths and kills

- Average deaths per knight per game: ${(deaths / (GAMES * PLAYERS)).toFixed(2)}
- Average fights won per knight per game: ${(kills / (GAMES * PLAYERS)).toFixed(2)} (monster fights and duels)

### Item usage

Weapons and armor are counted in combat rounds fought with them equipped; consumables in times used.

Most used:

| Item | Type | Count |
| --- | --- | --- |
${used.slice(0, 5).map(row).join('\n')}

Least used:

| Item | Type | Count |
| --- | --- | --- |
${used.slice(-5).reverse().map(row).join('\n')}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, report);
console.log(report);
